static void DestroyEmote(struct Sprite *sprite)
{
    FreeSpriteTilesByTag(EMOTE_TAG);
    FreeSpritePaletteByTag(EMOTE_TAG);
    DestroySprite(sprite);
}

static void SpriteCB_FollowerEmote(struct Sprite *sprite)
{
    struct Sprite *followerSprite;
    u8 frame = sprite->data[0];

    if (frame >= EMOTE_DURATION || !IsFollowerPokemon())
    {
        DestroyEmote(sprite);
        return;
    }

    followerSprite = &gSprites[gEventObjects[gFollowerState.objId].spriteId];
    sprite->pos1.x = followerSprite->pos1.x;
    sprite->pos1.y = followerSprite->pos1.y + followerSprite->centerToCornerVecY - 4;
    sprite->pos2.y = frame < 4 ? -(frame * 2) : -8 + ((frame / 8) & 1);
    sprite->data[0]++;
}

void CreateFollowerEmote(u8 emote)
{
    struct Sprite *followerSprite;
    u8 spriteId;

    if (emote >= FOLLOWER_EMOTE_COUNT || !IsFollowerPokemon())
        return;

    if (GetSpriteTileStartByTag(EMOTE_TAG) != 0xFFFF)
        return;

    followerSprite = &gSprites[gEventObjects[gFollowerState.objId].spriteId];

    LoadSpriteSheet(&sEmoteSheet);
    LoadSpritePalette(&sEmotePal);
    spriteId = CreateSprite(&sEmoteTemplate, followerSprite->pos1.x, followerSprite->pos1.y + followerSprite->centerToCornerVecY - 4, 0);

    if (spriteId >= MAX_SPRITES)
    {
        FreeSpriteTilesByTag(EMOTE_TAG);
        FreeSpritePaletteByTag(EMOTE_TAG);
        return;
    }

    gSprites[spriteId].data[0] = 0;
    gSprites[spriteId].coordOffsetEnabled = TRUE;
    StartSpriteAnim(&gSprites[spriteId], emote);
}
